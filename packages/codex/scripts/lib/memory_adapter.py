#!/usr/bin/env python3
"""Authoritative typed-memory adapter over the `muninn` CLI (subprocess only; muninn needs py3.12, Coderails is py3.9).

Muninn is the default and only store: `memory.backend: muninn|off` (config key `memory`, default muninn). A missing,
old or refusing muninn never falls back to Markdown; every failure returns `Degraded(reason)` (CLI exit 3, reason
printed as JSON) and appends a fail-open trace row (command `memory.<op>`). Reason codes and remediations:
memory_reasons.REASONS. A muninn refusal (rc 2, {"error": c}) becomes `refused_<c>`. Cites must anchor in a user prompt
(memory_cite). Markdown is only ever a generated view written through `write_view`.
"""

from __future__ import annotations

import argparse
import contextlib
import dataclasses
import importlib.util
import json
import os
import re
import runpy
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any, cast

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # plugin root, so `scripts.lib` resolves as a script
from scripts.lib import memory_cite, memory_read, memory_schema  # noqa: E402

_expired = memory_read.expired  # direct alias for the existing caller contract

TIMEOUT = 10.0
MARKER = "<!-- generated by memory_adapter -->"
SCOPES = ("user", "project", "repository", "loop")
TYPES = memory_read.TYPES
CONFIDENCE = ("observed", "reported", "inferred")
ADD_FLAGS = ("--scope-loop", "--confidence", "--valid-until", "--sensitivity", "--contradicts", "--tag")
KINDS = ("lesson", "constraint")  # the help text must advertise the typed kinds too
TAG, DATE, KID = memory_read.TAG, memory_read.DATE, memory_read.KID
CODE = re.compile(r"[a-z][a-z_]{0,40}")
NO_SESSION = "memory-adapter-nosession"  # trace dir used when no session id is given
PROBE_LOOP = "memory-probe"  # scope id for the read smoke
PROBE_CACHE: dict[str, str | None] = {}


@dataclasses.dataclass
class Degraded:
    """A refusal or degrade; `reason` is a low-cardinality code."""

    reason: str
    detail: str = dataclasses.field(default="", compare=False)  # e.g. the original muninn refusal code


@dataclasses.dataclass
class Written:
    """A successful write; `id` is muninn's K<n>."""

    id: str


@dataclasses.dataclass
class Record:
    """One typed memory record; id/created_at are filled from muninn on read."""

    scope: str
    type: str
    claim: str
    cite: str
    quote: str
    tags: list[str] = dataclasses.field(default_factory=list[str])
    loop_id: str | None = None
    confidence: str | None = None
    valid_until: str | None = None
    supersedes: str | None = None
    contradicts: str | None = None
    sensitivity: str = "normal"
    id: str | None = None
    created_at: str | None = None
    cite_role: str = ""  # declared anchor of `cite`; empty is cite_not_user. The CLI resolves it from the session
    cite_kind: str = ""
    reply_cite: str = ""  # approved_reply form: the proposing reply (cite/quote then hold the approval)
    reply_quote: str = ""


def validate(r: Record) -> str | None:
    """Return a reason code when the record may not be written, else None."""
    if not r.quote.strip():
        return "uncited_write"
    if r.sensitivity == "restricted":
        return "restricted_refused"
    ok = (
        r.scope in SCOPES
        and r.type in TYPES
        and bool(r.claim.strip())
        and r.sensitivity == "normal"
        and (r.confidence is None or r.confidence in CONFIDENCE)
        and (r.valid_until is None or DATE.fullmatch(r.valid_until) is not None)
        and all(TAG.fullmatch(t) for t in r.tags)
        and (r.scope != "loop" or bool(r.loop_id))
        and all(k is None or KID.fullmatch(k) for k in (r.supersedes, r.contradicts))
    )
    return memory_cite.check(r) if ok else "bad_record"


def backend() -> str:
    """The configured `memory.backend` (default muninn), read via scripts.lib.config like every other key."""
    try:
        spec = importlib.util.spec_from_file_location("_coderails_config", Path(__file__).with_name("config.py"))
        mod = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
        sys.modules["_coderails_config"] = mod
        spec.loader.exec_module(mod)  # type: ignore[union-attr]
        path = mod.config_path()
        return (mod.config_value(path, "backend", "memory") if path else "") or "muninn"
    except Exception:  # an unreadable config keeps the default: muninn stays authoritative
        return "muninn"


def _trace(op: str, reason: str, session_id: str, loop_id: str | None, detail: str = "") -> None:
    """Append a fail-open trace row via hooks/scripts/lib/trace_row.py when this layout ships it."""
    session_id = session_id or NO_SESSION
    try:
        path = Path(__file__).resolve().parents[2] / "hooks/scripts/lib/trace_row.py"
        inputs = {"muninn_error": detail} if detail else None  # stored as a sha256, like every trace input
        runpy.run_path(str(path))["append_row"](f"memory.{op}", "degraded", reason, session_id, loop_id, inputs)
    except Exception:  # fail open: tracing never blocks memory
        return


def _refusal(stdout: str) -> Degraded | None:
    """Map a muninn refusal (rc 2, stdout {"error": c}) to `refused_<c>`, keeping c as the detail."""
    try:
        code = json.loads(stdout).get("error")
    except (ValueError, AttributeError):
        return None
    return Degraded(f"refused_{code}", code) if isinstance(code, str) and CODE.fullmatch(code) else None


def _run(args: list[str], help_probe: bool = False) -> str | Degraded:
    exe = shutil.which("muninn")
    if exe is None:
        return Degraded("muninn_absent")
    try:
        p = subprocess.run([exe, *args], capture_output=True, text=True, timeout=TIMEOUT)
    except subprocess.TimeoutExpired:
        return Degraded("muninn_timeout")
    except OSError:
        return Degraded("muninn_error")
    if help_probe:  # the live binary prints --help on stderr with rc 2; 0.1.0 prints no flags: judge the text
        return (p.stdout + p.stderr) or Degraded("muninn_old_ledger")
    if p.returncode == 0:
        return p.stdout
    return (_refusal(p.stdout) if p.returncode == 2 else None) or Degraded("muninn_error")


def probe() -> Degraded | None:
    """Backend switch, muninn on PATH, the Part A help flags, the store schema, then one read smoke."""
    mode = backend()
    if mode != "muninn":
        return Degraded("memory_backend_off" if mode == "off" else "memory_backend_invalid")
    key = shutil.which("muninn") or ""
    if key not in PROBE_CACHE:
        add_help, list_help = _run(["know", "add", "--help"], True), _run(["know", "list", "--help"], True)
        failed = next((h for h in (add_help, list_help) if isinstance(h, Degraded)), None)
        flags = any(f not in str(add_help) for f in (*ADD_FLAGS, *KINDS)) or "--scope-loop" not in str(list_help)
        PROBE_CACHE[key] = failed.reason if isinstance(failed, Degraded) else "muninn_old_ledger" if flags else None
    reason = PROBE_CACHE[key] or memory_schema.check()  # the schema is read every time: it can change under us
    smoke = f"{key}|{memory_schema.store_path()}|smoke"
    if reason is None and smoke not in PROBE_CACHE:
        got = _run(["know", "list", "--scope-loop", PROBE_LOOP, "--status", "all"])
        if isinstance(got, Degraded):
            reason = got.reason
        else:
            PROBE_CACHE[smoke] = None
    return Degraded(reason) if reason else None


def _fail(op: str, reason: str | Degraded, session_id: str, loop_id: str | None = None) -> Degraded:
    d = Degraded(reason) if isinstance(reason, str) else reason
    _trace(op, d.reason, session_id, loop_id, d.detail)
    return d


def add(r: Record, session_id: str = "") -> Written | Degraded:
    """Write one cited record via `muninn know add`; `Written(id)` on success."""
    bad = validate(r)
    if bad:
        return _fail("add", bad, session_id, r.loop_id)
    down = probe()
    if down:
        return _fail("add", down, session_id, r.loop_id)
    argv = ["know", "add", "--kind", r.type, "--text", r.claim, *memory_cite.argv(r), "--sensitivity", r.sensitivity]
    argv += ["--scope-loop", r.loop_id or ""] if r.scope == "loop" else ["--global"] if r.scope == "user" else []
    for flag, val in (("--confidence", r.confidence), ("--valid-until", r.valid_until), ("--supersedes", r.supersedes)):
        argv += [flag, val] if val else []
    argv += ["--contradicts", r.contradicts] if r.contradicts else []
    for t in r.tags:
        argv += ["--tag", t]
    out = _run(argv)
    if isinstance(out, Degraded):
        return _fail("add", out, session_id, r.loop_id)
    try:
        kid = str(json.loads(out)["entry"]["id"])
    except (ValueError, KeyError, TypeError):
        kid = ""
    return Written(kid) if KID.fullmatch(kid) else _fail("add", "muninn_bad_output", session_id, r.loop_id)


def _search_ids(query: str, scope: str, loop_id: str | None) -> set[str] | Degraded:
    """Ids of `muninn search <q> --all-projects` knowledge hits, filtered to scope loop:<id> for loop reads."""
    out = _run(["search", query, "--all-projects"])
    if isinstance(out, Degraded):
        return out
    try:
        hits = cast("list[dict[str, Any]]", json.loads(out)["knowledge"])
        return {str(h["id"]) for h in hits if scope != "loop" or h.get("scope") == f"loop:{loop_id}"}
    except (ValueError, KeyError, TypeError, AttributeError):
        return Degraded("muninn_error")


def list_records(
    scope: str,
    loop_id: str | None = None,
    type: str | None = None,
    tags: list[str] | None = None,
    query: str | None = None,
    session_id: str = "",
) -> list[Record] | Degraded:
    """Return current, non-expired, non-restricted records with provenance (muninn id, cite, quote)."""
    if scope == "loop" and not loop_id:
        return _fail("list", "bad_record", session_id, loop_id)  # unfiltered rows would be mislabeled loop-scoped
    down = probe()
    if down:
        return _fail("list", down, session_id, loop_id)
    argv = ["know", "list", "--status", "current"]
    argv += ["--kind", type] if type else []
    argv += ["--scope-loop", loop_id] if scope == "loop" and loop_id else []
    out = _run(argv)
    if isinstance(out, Degraded):
        return _fail("list", out, session_id, loop_id)
    wanted = _search_ids(query, scope, loop_id) if query else None
    if isinstance(wanted, Degraded):
        return _fail("list", wanted, session_id, loop_id)
    try:
        raw: object = json.loads(out)["entries"]
        entries = cast("list[Any]", raw)
        if not isinstance(raw, list):
            return _fail("list", "muninn_error", session_id, loop_id)
        if any(not isinstance(e, dict) for e in entries):
            return _fail("list", "muninn_error", session_id, loop_id)
        found: list[Record] = []
        for e in entries:
            cite = memory_read.anchor(e)
            if cite is None or type and e["kind"] != type:
                continue
            label = cast("str", e["scope"])  # anchor validated the scope; muninn lists global plus repo without loop
            if (scope in ("project", "repository") and (label == "global" or label.startswith("loop:"))) or (
                scope == "user" and label != "global"
            ):
                continue
            if scope == "loop" and label != f"loop:{loop_id}":
                continue
            if tags and not set(tags) <= set(e.get("tags") or []):
                continue
            if wanted is not None and str(e["id"]) not in wanted:
                continue
            found.append(
                Record(
                    scope=scope,
                    type=e["kind"],
                    claim=e["text"],
                    cite=cite.get("ref", ""),
                    quote=cite.get("quote", ""),
                    tags=list(e.get("tags") or []),
                    loop_id=loop_id,
                    confidence=e.get("confidence"),
                    valid_until=e.get("valid_until"),
                    id=e["id"],
                    created_at=e.get("date"),
                    cite_role="user",
                    cite_kind="prompt",
                )
            )
        return found
    except (ValueError, KeyError, TypeError, AttributeError):
        return _fail("list", "muninn_error", session_id, loop_id)


def render(records: list[Record], title: str = "Memory Index") -> str:
    """Render records as a marker-stamped Markdown view."""
    lines = [MARKER, f"# {title}", ""]
    lines += [f"- [{r.id}] ({r.type}) {' '.join(r.claim.split())} -- cite `{r.cite}`" for r in records]
    return "\n".join(lines) + "\n"


def write_view(path: Path, text: str, session_id: str = "") -> Degraded | None:
    """Atomically write a generated view, only over an absent or marker-stamped file."""
    path = Path(path)
    if path.exists():
        try:
            first = path.read_text(encoding="utf-8").split("\n", 1)[0]
        except OSError:
            return _fail("render", "muninn_error", session_id)
        if first != MARKER:
            return _fail("render", "handwritten_protected", session_id)
    tmp = None
    try:
        fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=path.name + ".tmp")
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
        return None
    except OSError:
        if tmp:
            with contextlib.suppress(OSError):
                os.unlink(tmp)
        return _fail("render", "muninn_error", session_id)


def resolve_cite(r: Record, approval: bool, session_id: str = "") -> Degraded | None:
    """CLI path: set the cite role/kind (and an approval's reply) from the caller's own `muninn session <id>`."""
    down = probe()
    root = memory_cite.session_of(r.cite) if r.cite else session_id
    out = down or (_run(["session", root]) if root else Degraded("cite_unresolved"))
    if isinstance(out, Degraded):
        return _fail("add", out, session_id, r.loop_id)
    try:
        payload = cast("dict[str, Any]", json.loads(out))
    except ValueError:
        return _fail("add", "muninn_error", session_id, r.loop_id)
    bad = memory_cite.resolve(r, payload, approval, session_id)
    return _fail("add", bad, session_id, r.loop_id) if bad else None


def main(argv: list[str] | None = None) -> int:
    """CLI: add|list|render|probe. Exit 0 ok, 3 degraded (reason on stdout as JSON)."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("cmd", choices=("add", "list", "render", "probe"))
    for flag in ("--type", "--loop", "--claim"):
        ap.add_argument(flag)
    ap.add_argument("--scope", default="loop", choices=SCOPES)
    ap.add_argument("--run", help="adds tag run-<id[:28]>")
    ap.add_argument("--cite", default="", help="ref of a user prompt; role is verified from the session")
    ap.add_argument("--quote", default="", help="verbatim quote; alone it cites the caller session's own prompt")
    ap.add_argument("--approval", default="", help="ref of a short user approval; its preceding reply is cited too")
    for flag in ("--confidence", "--valid-until", "--supersedes", "--contradicts", "--query"):
        ap.add_argument(flag)
    ap.add_argument("--tag", action="append", default=[])
    sid = os.environ.get("CLAUDE_SESSION_ID") or os.environ.get("CLAUDE_CODE_SESSION_ID")
    sid = sid or os.environ.get("CODEX_SESSION_ID") or os.environ.get("CODEX_THREAD_ID", "")
    ap.add_argument("--session", default=sid)
    ap.add_argument("--memory-md", action="store_true")
    ap.add_argument("--write", metavar="PATH")
    a = ap.parse_args(argv)
    tags: list[str] = a.tag + ([f"run-{a.run[:28].lower()}"] if a.run else [])
    res: Degraded | Written | None = None
    if a.cmd == "probe":
        res = probe()
    elif a.cmd == "add":
        rec = Record(a.scope, a.type or "", a.claim or "", a.approval or a.cite, a.quote, tags, a.loop)
        for name in ("confidence", "valid_until", "supersedes", "contradicts"):
            setattr(rec, name, getattr(a, name))
        res = resolve_cite(rec, bool(a.approval), a.session)  # always: a quote-only cite is verified too
        res = res or add(rec, a.session)
    else:
        found = list_records(a.scope, a.loop, a.type, tags, a.query, a.session)
        if isinstance(found, Degraded):
            res = found
        elif a.cmd == "list":
            print(json.dumps([dataclasses.asdict(r) for r in found], indent=2))
        else:
            text = render(found, "Memory Index")
            if a.write:
                res = write_view(Path(a.write), text, a.session)
            else:
                sys.stdout.write(text)  # dry-run by default
    if isinstance(res, Degraded):
        print(json.dumps({"degraded": res.reason}))
        return 3
    if isinstance(res, Written):
        print(json.dumps({"ok": True, "id": res.id}))
    elif a.cmd in ("add", "probe"):
        print(json.dumps({"ok": True}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
